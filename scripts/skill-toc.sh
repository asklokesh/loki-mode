#!/usr/bin/env bash
# Maintain the generated table of contents at the top of every skills/*.md
# longer than 100 lines, so a partial read still shows the whole module scope.
#   scripts/skill-toc.sh           rewrite stale or missing TOCs in place
#   scripts/skill-toc.sh --check   exit 1 and name each stale or missing file
# The TOC lives between TOC:START and TOC:END markers right after the H1 and is
# excluded from the line count, so adding it never changes whether a file needs it.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MIN_LINES=100
START='<!-- TOC:START (generated by scripts/skill-toc.sh; do not edit) -->'
END='<!-- TOC:END -->'
MODE="${1:-write}"

# Print the file without its TOC block.
strip_toc() {
    awk -v s="$START" -v e="$END" '
        $0 == s { skip = 1; next }
        skip && $0 == e { skip = 0; getline nxt; if (nxt != "") print nxt; next }
        !skip { print }
    ' "$1"
}

# Print the file with a fresh TOC inserted after the first H1 (outside fences).
render() {
    strip_toc "$1" | awk -v s="$START" -v e="$END" '
        { lines[NR] = $0 }
        END {
            fence = 0; h1 = 0; n = 0
            for (i = 1; i <= NR; i++) {
                l = lines[i]
                if (l ~ /^(```|~~~)/) { fence = !fence; continue }
                if (fence) continue
                if (!h1 && l ~ /^# /) { h1 = i; continue }
                if (l ~ /^##+ /) {
                    depth = match(l, /[^#]/) - 1
                    if (depth > 3) continue
                    t = substr(l, depth + 2)
                    gsub(/[ \t]+$/, "", t)
                    slug = tolower(t)
                    gsub(/[^a-z0-9 _-]/, "", slug)
                    gsub(/ /, "-", slug)
                    seen[slug]++
                    if (seen[slug] > 1) slug = slug "-" (seen[slug] - 1)
                    n++
                    pad = (depth == 3) ? "  " : ""
                    toc[n] = pad "- [" t "](#" slug ")"
                }
            }
            for (i = 1; i <= NR; i++) {
                print lines[i]
                if (i == h1) {
                    print ""
                    print s
                    print "## Contents"
                    print ""
                    for (j = 1; j <= n; j++) print toc[j]
                    print e
                }
            }
        }
    '
}

status=0
for f in "$ROOT"/skills/*.md; do
    rel="skills/$(basename "$f")"
    body_lines=$(strip_toc "$f" | wc -l | tr -d ' ')
    [ "$body_lines" -gt "$MIN_LINES" ] || continue
    want="$(render "$f")"
    if [ "$want" = "$(cat "$f")" ]; then
        continue
    fi
    if [ "$MODE" = "--check" ]; then
        echo "STALE: $rel (run scripts/skill-toc.sh)"
        status=1
    else
        printf '%s\n' "$want" > "$f"
        echo "updated $rel"
    fi
done
exit "$status"
