// project_model/linguist.ts -- byte-weighted language attribution with github-linguist's vendored/documentation/generated rules and .gitattributes overrides (D122).
// New file: no existing module owns language attribution. Rule data lives in linguist_rules.json, which is vendored third-party data. The generated-file heuristics below
// are the header and name checks of linguist's generated.rb v9.4.0 (same source, same license), kept as code because they test file content. Pure read; never throws.
import { closeSync, lstatSync, openSync, readSync } from "node:fs";
import { extname, join } from "node:path";
import { safeGit } from "../util/safe_git.ts";
import { LOCK_RULES } from "../util/lock_ecosystems.ts";
import rules from "./linguist_rules.json" with { type: "json" };

export interface LinguistAttrs { vendored?: boolean; generated?: boolean; documentation?: boolean; detectable?: boolean; language?: string }
const VENDOR_RES = (rules.vendor as readonly string[]).map((p) => new RegExp(p)), DOC_RES = (rules.documentation as readonly string[]).map((p) => new RegExp(p));
const LOCKFILES = new Set<string>([...LOCK_RULES.flatMap((r) => r.locks), "go.sum"]); // lock names come from the one lock-ecosystem table, never a second literal list
const LOCKFILE_RE = { test: (path: string): boolean => LOCKFILES.has(path.slice(path.lastIndexOf("/") + 1)) };
const GENERATED_NAME_RE = /(\.min\.(js|css)|\.(js|css)\.map|\.designer\.cs|\.Designer\.vb|\.pbxproj)$/i;
const PROTOBUF_EXT = /^\.(py|java|h|cc|cpp|m|rb|php)$/, THRIFT_EXT = /^\.(rb|py|go|js|m|java|h|cc|cpp|php)$/;
/** [extension, header regex, how many leading lines it may appear in]; each mirrors one generated.rb check. */
const HEADER_RULES: ReadonlyArray<readonly [RegExp, RegExp, number]> = [
  [/^\.go$/, /^\/\/ Code generated /m, 40], [PROTOBUF_EXT, /Generated by the protocol buffer compiler\.  DO NOT EDIT!/, 3], [THRIFT_EXT, /Autogenerated by Thrift Compiler/, 6],
  [/^\.(h|cc|cpp|hpp)$/, /^\/\/ Generated by the gRPC/, 1], [/^\.ts$/, /Code generated by protoc-gen-ts_proto\. DO NOT EDIT\./, 1], [/^\.(c|cpp)$/, /Generated by Cython/, 1],
  [/^\.js$/, /^\/\/ Generated by |Generated by PEG\.js|^\/\* (parser generated by jison|generated by jison-lex) /m, 5], [/^\.dart$/, /generated code\W{2,3}do not modify/i, 3],
];
const HEAD_BYTES = 4096, HEAD_EXTS = /^\.(go|py|java|h|cc|cpp|hpp|m|rb|php|ts|c|js|dart|css)$/;
const readHead = (abs: string): string => {
  let fd = -1;
  try { fd = openSync(abs, "r"); const buf = Buffer.alloc(HEAD_BYTES); return buf.toString("utf8", 0, readSync(fd, buf, 0, HEAD_BYTES, 0)); } catch { return ""; } finally { if (fd >= 0) try { closeSync(fd); } catch { /* ignore */ } }
};
const generatedByRules = (path: string, head: string): boolean => {
  if (LOCKFILE_RE.test(path) || GENERATED_NAME_RE.test(path)) return true;
  const ext = extname(path), lower = ext.toLowerCase();
  if (head === "") return false;
  const lines = head.split("\n");
  if ((lower === ".js" || lower === ".css") && head.length / lines.length > 110) return true; // linguist's minified heuristic: mean line length above 110
  return HEADER_RULES.some(([e, re, n]) => e.test(ext) && re.test(lines.slice(0, n).join("\n")));
};
/** The one predicate: true when the file does not count toward language statistics. An explicit .gitattributes value (linguist-vendored, -generated, -documentation) beats the built-in rules; linguist-detectable=true always counts. */
export function isVendoredOrGenerated(path: string, attrs: LinguistAttrs = {}, head = ""): boolean {
  if (attrs.detectable === true) return false;
  return (attrs.vendored ?? VENDOR_RES.some((re) => re.test(path))) || (attrs.documentation ?? DOC_RES.some((re) => re.test(path))) || (attrs.generated ?? generatedByRules(path, head));
}
const ATTR_NAMES = ["linguist-vendored", "linguist-generated", "linguist-documentation", "linguist-language", "linguist-detectable"] as const;
const truth = (v: string): boolean | undefined => (v === "set" || v === "true" ? true : v === "unset" || v === "false" ? false : undefined);
/** .gitattributes linguist-* values for `files`, read with `git check-attr` (the repo's own in-tree attributes; empty outside a git repo). */
export function readLinguistAttrs(root: string, files: readonly string[]): Map<string, LinguistAttrs> {
  const out = new Map<string, LinguistAttrs>();
  if (files.length === 0) return out;
  let raw = "";
  try { raw = safeGit(root, ["check-attr", "-z", "--stdin", ...ATTR_NAMES], { input: files.join("\0") + "\0", stdio: ["pipe", "pipe", "ignore"], maxBuffer: 1 << 28 }); } catch { return out; }
  const parts = raw.split("\0");
  for (let i = 0; i + 2 < parts.length; i += 3) {
    const [path, attr, value] = [parts[i]!, parts[i + 1]!, parts[i + 2]!];
    if (value === "unspecified") continue;
    const a = out.get(path) ?? {};
    if (attr === "linguist-language") { if (value !== "unset" && value !== "set") a.language = value; }
    else { const b = truth(value); if (b !== undefined) a[attr.slice(9) as "vendored" | "generated" | "documentation" | "detectable"] = b; }
    out.set(path, a);
  }
  return out;
}
/** Blob bytes per path from `git ls-tree -r -l HEAD`; paths git does not list (uncommitted, no repo) fall back to lstat. */
function blobBytes(root: string, files: readonly string[]): Map<string, number> {
  const sizes = new Map<string, number>();
  try { for (const rec of safeGit(root, ["ls-tree", "-r", "-l", "-z", "HEAD"], { maxBuffer: 1 << 28 }).split("\0")) { const m = /^\d+ blob \S+ +(\d+)\t(.*)$/s.exec(rec); if (m) sizes.set(m[2]!, Number(m[1])); } } catch { /* no HEAD */ }
  for (const f of files) if (!sizes.has(f)) { try { sizes.set(f, lstatSync(join(root, f)).size); } catch { /* gone */ } }
  return sizes;
}
/** linguist-language names that map onto an extension the caller's classifier understands; any other name is treated as not source. */
const LANG_EXT = rules.languageExtensions as Readonly<Record<string, string>>;
/** Bytes per language bucket. `classify(path)` buckets a path (null: not source). Vendored, documentation and generated files are dropped, linguist-language overrides the bucket, and without a root every file weighs 1 and only path rules apply. */
export function languageBytes(root: string | undefined, files: readonly string[], classify: (path: string) => string | null): Map<string, number> {
  const out = new Map<string, number>(), attrs = root ? readLinguistAttrs(root, files) : new Map<string, LinguistAttrs>(), sizes = root ? blobBytes(root, files) : new Map<string, number>();
  for (const f of files) {
    const a = attrs.get(f) ?? {}, ext = extname(f), head = root && HEAD_EXTS.test(ext.toLowerCase()) && a.generated === undefined ? readHead(join(root, f)) : "";
    if (isVendoredOrGenerated(f, a, head)) continue;
    const bucket = a.language !== undefined ? ((e) => (e ? classify(`override${e}`) : null))(LANG_EXT[a.language.toLowerCase()]) : classify(f);
    if (bucket !== null) out.set(bucket, (out.get(bucket) ?? 0) + Math.max(root ? sizes.get(f) ?? 0 : 1, 1));
  }
  return out;
}
/** Paths of `files` that isVendoredOrGenerated drops, for ordering a capped file list (repomap). Reads .gitattributes and file heads like languageBytes. */
export function excludedPaths(root: string, files: readonly string[]): Set<string> {
  const attrs = readLinguistAttrs(root, files);
  return new Set(files.filter((f) => { const a = attrs.get(f) ?? {}; return isVendoredOrGenerated(f, a, HEAD_EXTS.test(extname(f).toLowerCase()) && a.generated === undefined ? readHead(join(root, f)) : ""); }));
}
